_language = AssistantLanguage.TURKISH


def use(language: AssistantLanguage) -> None:
    global _language
    _language = language


def t(key: str, **values: object) -> str:
    texts = _ENGLISH if _language is AssistantLanguage.ENGLISH else _TURKISH
    return texts[key].format(**values) if values else texts[key]
